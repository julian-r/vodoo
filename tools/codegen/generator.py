def _load_spec(root: Path, path: Path = SPEC_PATH) -> NamespaceSpec:
    raw: Any = yaml.safe_load((root / path).read_text(encoding="utf-8"))
    return NamespaceSpec.model_validate(raw)


def _load_security_groups(root: Path) -> SecurityGroupsSpec:
    raw: Any = yaml.safe_load((root / SECURITY_GROUPS_SPEC_PATH).read_text(encoding="utf-8"))
    return SecurityGroupsSpec.model_validate(raw)


def _load_specs(root: Path) -> tuple[NamespaceSpec, ...]:
    paths = sorted((root / SPEC_DIR).glob(SPEC_GLOB))
    if not paths:
        raise FileNotFoundError(f"No namespace specifications found under {root / SPEC_DIR}")
    specs_list: list[NamespaceSpec] = []
    for path in paths:
        spec = _load_spec(root, path.relative_to(root))
        if path.stem != spec.namespace:
            raise ValueError(f"spec filename {path.name!r} must match namespace {spec.namespace!r}")
        specs_list.append(spec)
    specs = tuple(specs_list)
    namespaces = [spec.namespace for spec in specs]
    if len(namespaces) != len(set(namespaces)):
        raise ValueError("namespace specifications must have unique namespace names")
    class_names = [spec.class_name for spec in specs]
    if len(class_names) != len(set(class_names)):
        raise ValueError("namespace specifications must have unique class names")
    return specs


def _source_path(spec: NamespaceSpec) -> Path:
    return SPEC_DIR / f"{spec.namespace}.yaml"


def _output_paths(spec: NamespaceSpec) -> tuple[Path, Path, Path, Path]:
    stem = spec.namespace
    swift_stem = "".join(part.title() for part in stem.split("_"))
    return (
        TYPESCRIPT_OUTPUT_DIR / f"{stem}.ts",
        PYTHON_OUTPUT_DIR / f"{stem}.py",
        ASYNC_PYTHON_OUTPUT_DIR / f"{stem}.py",
        SWIFT_OUTPUT_DIR / f"{swift_stem}.swift",
    )


def all_output_paths(root: Path | None = None) -> tuple[Path, ...]:
    root = root or Path.cwd()
    return (
        *(path for spec in _load_specs(root) for path in _output_paths(spec)),
        PYTHON_SECURITY_GROUPS_PATH,
        TYPESCRIPT_SECURITY_GROUPS_PATH,
        API_MANIFEST_PATH,
    )


def _snake_case(value: str) -> str:
    with_word_boundaries = re.sub(r"(.)([A-Z][a-z]+)", r"\1_\2", value)
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", with_word_boundaries).lower()


def _constant_prefix(spec: NamespaceSpec) -> str:
    return _snake_case(spec.class_name).upper()


def _typescript_constant_name(spec: NamespaceSpec, value: str) -> str:
    return f"{_constant_prefix(spec)}_{_snake_case(value).upper()}"


def _python_constant_name(value: str) -> str:
    snake = _snake_case(value)
    if snake.endswith("ies"):
        snake = f"{snake[:-3]}y"
    elif snake.endswith("s"):
        snake = snake[:-1]
    return f"{snake.upper()}_FIELDS"


def _typescript_literal(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def _typescript_doc(value: str) -> str:
    return value.replace("*/", "*\\/").replace("\n", "\n   * ")


def _python_literal(value: object) -> str:  # noqa: PLR0911
    if value is None:
        return "None"
    if value is True:
        return "True"
    if value is False:
        return "False"
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, int | float):
        return repr(value)
    if isinstance(value, list):
        return "[" + ", ".join(_python_literal(item) for item in value) + "]"
    if isinstance(value, dict):
        pairs = (f"{_python_literal(key)}: {_python_literal(item)}" for key, item in value.items())
        return "{" + ", ".join(pairs) + "}"
    raise TypeError(f"Unsupported generated literal: {type(value).__name__}")


def _python_string_list(values: list[str], *, indent: int = 0) -> str:
    prefix = " " * indent
    item_prefix = " " * (indent + 4)
    lines = ["["]
    lines.extend(f"{item_prefix}{_python_literal(value)}," for value in values)
    lines.append(f"{prefix}]")
    return "\n".join(lines)


def _spec_digest(spec: NamespaceSpec) -> str:
    canonical = json.dumps(spec.model_dump(mode="json", by_alias=True), sort_keys=True).encode()
    return hashlib.sha256(canonical).hexdigest()[:16]


def _render_typescript_search_read(
    spec: NamespaceSpec,
    operation: SearchReadOperation,
) -> str:
    fields = _typescript_constant_name(spec, operation.fields)
    domain = operation.domain
    if domain is None:
        signature = "()"
        domain_line = "const domain: Domain = [];"
    elif isinstance(domain, OptionalListDomain):
        signature = f"({domain.parameter}: number | null = null)"
        domain_line = (
            f"const domain: Domain = {domain.parameter} === null ? [] : "
            f"[[{_typescript_literal(domain.field)},{_typescript_literal(domain.operator)},"
            f"[{domain.parameter}]]];"
        )
    elif isinstance(domain, OptionalDomain):
        signature = f"({domain.parameter}: number | null = null)"
        domain_line = (
            f"const domain: Domain = {domain.parameter} === null ? [] : "
            f"[[{_typescript_literal(domain.field)},{_typescript_literal(domain.operator)},"
            f"{domain.parameter}]];"
        )
    elif isinstance(domain, RequiredDomain):
        signature = f"({domain.parameter}: number)"
        domain_line = (
            f"const domain: Domain = [[{_typescript_literal(domain.field)},"
            f"{_typescript_literal(domain.operator)},{domain.parameter}]];"
        )
    else:  # pragma: no cover - discriminated validation makes this unreachable
        raise AssertionError("unknown domain")
    request = f"""this.client.searchRead({_typescript_literal(operation.model)}, {{
      domain,
      fields: {fields},
      order: {_typescript_literal(operation.order)},
    }})"""
    date_fields = spec.field_set_date_fields.get(operation.fields)
    if date_fields:
        date_constant = _typescript_constant_name(spec, f"{operation.fields}DateFields")
        result = (
            f"const records = await {request};\n"
            f"    return records.map((record) => decodeRecordDates(record, {date_constant}));"
        )
    else:
        result = f"return {request};"
    return f"""  /** {_typescript_doc(operation.description)} */
  async {operation.name}{signature}: Promise<OdooRecord[]> {{
    {domain_line}
    {result}
  }}"""


def _render_typescript_write(operation: WriteOperation) -> str:
    return f"""  /** {_typescript_doc(operation.description)} */
  {operation.name}({operation.id_parameter}: number): Promise<boolean> {{
    return this.client.write(
      {_typescript_literal(operation.model)},
      [{operation.id_parameter}],
      {_typescript_literal(operation.values)},
    );
  }}"""


def render_typescript(spec: NamespaceSpec) -> str:
    digest = _spec_digest(spec)
    prefix = _constant_prefix(spec)
    source_path = _source_path(spec)
    record_types = (
        "Domain, OdooRecord"
        if any(isinstance(operation, SearchReadOperation) for operation in spec.operations)
        else "OdooRecord"
    )
    lines = [
        f"// {_GENERATED_MARKER}",
        f"// Source: {source_path.as_posix()}",
        f"// Spec digest: sha256:{digest}",
        "",
        'import type { OdooClientApi } from "../client-api.js";',
        'import { decodeRecordDates } from "../dates.js";',
        'import { DomainNamespace } from "../namespaces/domain.js";',
        f'import type {{ {record_types} }} from "../types.js";',
        "",
        f"export const {prefix}_MODEL = {_typescript_literal(spec.model)};",
        (
            f"export const {prefix}_DEFAULT_FIELDS = "
            f"{_typescript_literal(spec.default_fields)} as const;"
        ),
        (
            f"export const {prefix}_DEFAULT_DETAIL_FIELDS = "
            f"{_typescript_literal(spec.default_detail_fields)}"
            f"{' as const' if spec.default_detail_fields is not None else ''};"
        ),
        f"export const {prefix}_DATE_FIELDS = {_typescript_literal(spec.date_fields)} as const;",
        f"export const {prefix}_CAPABILITIES = {_typescript_literal(spec.capabilities)} as const;",
        (
            f"export const {prefix}_AVAILABILITY = "
            f"{_typescript_literal(spec.availability.model_dump(mode='json', by_alias=True))} "
            "as const;"
        ),
    ]
    for name, fields in spec.field_sets.items():
        lines.append(
            f"export const {_typescript_constant_name(spec, name)} = "
            f"{_typescript_literal(fields)} as const;"
        )
    for name, fields in spec.field_set_date_fields.items():
        lines.append(
            f"export const {_typescript_constant_name(spec, f'{name}DateFields')} = "
            f"{_typescript_literal(fields)} as const;"
        )
    lines.extend(
        [
            "",
            (
                f"export abstract class Generated{spec.class_name}Namespace "
                "extends DomainNamespace {"
            ),
            "  constructor(client: OdooClientApi) {",
            "    super(client, {",
            f"      model: {prefix}_MODEL,",
            f"      defaultFields: {prefix}_DEFAULT_FIELDS,",
            f"      capabilities: {prefix}_CAPABILITIES,",
            f"      availability: {prefix}_AVAILABILITY,",
        ]
    )
    if spec.default_detail_fields is not None:
        lines.append(f"      defaultDetailFields: {prefix}_DEFAULT_DETAIL_FIELDS,")
    if spec.tag_model is not None:
        lines.append(f"      tagModel: {_typescript_literal(spec.tag_model)},")
    lines.extend(
        [
            "    });",
            "  }",
            "",
            "  protected override decodeRecord(record: OdooRecord): OdooRecord {",
            f"    return decodeRecordDates(record, {prefix}_DATE_FIELDS);",
            "  }",
        ]
    )
    operations: list[str] = []
    for operation in spec.operations:
        if isinstance(operation, SearchReadOperation):
            operations.append(_render_typescript_search_read(spec, operation))
        elif isinstance(operation, WriteOperation):
            operations.append(_render_typescript_write(operation))
    if operations:
        lines.extend(["", "\n\n".join(operations)])
    lines.extend(["}", ""])
    return "\n".join(lines)


def _python_domain(operation: SearchReadOperation) -> tuple[str, list[str]]:
    domain = operation.domain
    if domain is None:
        return "self", ["domain: list[Any] = []"]

    parameter = _snake_case(domain.parameter)
    if isinstance(domain, OptionalListDomain):
        return (
            f"self, {parameter}: int | None = None",
            [
                "domain: list[Any] = []",
                f"if {parameter} is not None:",
                (
                    f"    domain.append(({_python_literal(domain.field)}, "
                    f"{_python_literal(domain.operator)}, [{parameter}]))"
                ),
            ],
        )
    if isinstance(domain, OptionalDomain):
        return (
            f"self, {parameter}: int | None = None",
            [
                "domain: list[Any] = []",
                f"if {parameter} is not None:",
                (
                    f"    domain.append(({_python_literal(domain.field)}, "
                    f"{_python_literal(domain.operator)}, {parameter}))"
                ),
            ],
        )
    if isinstance(domain, RequiredDomain):
        return (
            f"self, {parameter}: int",
            [
                (
                    f"domain: list[Any] = [({_python_literal(domain.field)}, "
                    f"{_python_literal(domain.operator)}, {parameter})]"
                )
            ],
        )
    raise AssertionError("unknown domain")  # pragma: no cover


def _render_python_search_read(operation: SearchReadOperation, *, async_mode: bool) -> str:
    signature, domain_lines = _python_domain(operation)
    if operation.python_keyword_only:
        signature = signature.replace("self, ", "self, *, ", 1)
    method_name = _snake_case(operation.name)
    await_prefix = "await " if async_mode else ""
    async_prefix = "async " if async_mode else ""
    fields = _python_constant_name(operation.fields)
    body = [
        f"    {async_prefix}def {method_name}({signature}) -> list[dict[str, Any]]:",
        f"        {_python_literal(operation.description)}",
    ]
    body.extend(f"        {line}" for line in domain_lines)
    body.extend(
        [
            f"        return {await_prefix}self._client.search_read(",
            f"            {_python_literal(operation.model)},",
            "            domain=domain,",
            f"            fields={fields},",
            f"            order={_python_literal(operation.order)},",
            "        )",
        ]
    )
    return "\n".join(body)


def _render_python_write(operation: WriteOperation, *, async_mode: bool) -> str:
    method_name = _snake_case(operation.name)
    parameter = _snake_case(operation.id_parameter)
    await_prefix = "await " if async_mode else ""
    async_prefix = "async " if async_mode else ""
    return "\n".join(
        [
            f"    {async_prefix}def {method_name}(self, {parameter}: int) -> bool:",
            f"        {_python_literal(operation.description)}",
            f"        return {await_prefix}self._client.write(",
            f"            {_python_literal(operation.model)},",
            f"            [{parameter}],",
            f"            {_python_literal(operation.values)},",
            "        )",
        ]
    )


def _python_operations(spec: NamespaceSpec, *, async_mode: bool) -> str:
    rendered: list[str] = []
    for operation in spec.operations:
        if isinstance(operation, SearchReadOperation):
            rendered.append(_render_python_search_read(operation, async_mode=async_mode))
        elif isinstance(operation, WriteOperation):
            rendered.append(_render_python_write(operation, async_mode=async_mode))
    return "\n\n".join(rendered)


def render_python(spec: NamespaceSpec) -> str:
    digest = _spec_digest(spec)
    source_path = _source_path(spec)
    class_name = spec.class_name
    typing_import = (
        "Any, ClassVar"
        if any(isinstance(operation, SearchReadOperation) for operation in spec.operations)
        else "ClassVar"
    )
    module_docstring = (
        f'"""Generated {class_name.lower()} namespace metadata and simple '
        'synchronous operations."""'
    )
    lines = [
        module_docstring,
        "",
        f"# {_GENERATED_MARKER}",
        f"# Source: {source_path.as_posix()}",
        f"# Spec digest: sha256:{digest}",
        "",
        "from __future__ import annotations",
        "",
        f"from typing import {typing_import}",
        "",
        "from vodoo._domain import DomainNamespace",
        "",
    ]
    for name, fields in spec.field_sets.items():
        lines.extend(
            [
                f"{_python_constant_name(name)}: list[str] = {_python_string_list(fields)}",
                "",
            ]
        )
    lines.append("")
    lines.extend(
        [
            f"class _Generated{class_name}Attrs:",
            f'    """Shared generated attributes for {class_name.lower()} namespaces."""',
            "",
            f"    _model = {_python_literal(spec.model)}",
            "    _capabilities: ClassVar[frozenset[str]] = frozenset(\n        "
            + _python_string_list(spec.capabilities, indent=8)
            + "\n    )",
            "    _availability: ClassVar[dict[str, object]] = {",
            f'        "module": {_python_literal(spec.availability.module)},',
            '        "editions": '
            + _python_string_list(spec.availability.editions, indent=8)
            + ",",
            f'        "minVersion": {spec.availability.min_version},',
            '        "maxVersion": ' + _python_literal(spec.availability.max_version) + ",",
            "    }",
        ]
    )
    if spec.tag_model is not None:
        lines.append(f"    _tag_model: ClassVar[str | None] = {_python_literal(spec.tag_model)}")
    lines.extend(
        [
            "    _default_fields: ClassVar[list[str]] = "
            + _python_string_list(spec.default_fields, indent=4),
            "    _default_detail_fields: ClassVar[list[str] | None] = "
            + (
                _python_string_list(spec.default_detail_fields, indent=4)
                if spec.default_detail_fields is not None
                else "None"
            ),
            f"    _record_type = {_python_literal(spec.record_type)}",
            "",
            "",
            (
                f"class Generated{class_name}Namespace("
                f"_Generated{class_name}Attrs, DomainNamespace):"
            ),
            f'    """Generated synchronous {class_name.lower()} namespace operations."""',
        ]
    )
    operations = _python_operations(spec, async_mode=False)
    if operations:
        lines.extend(["", operations])
    lines.append("")
    return "\n".join(lines)


def render_async_python(spec: NamespaceSpec) -> str:
    digest = _spec_digest(spec)
    source_path = _source_path(spec)
    class_name = spec.class_name
    uses_any = any(isinstance(operation, SearchReadOperation) for operation in spec.operations)
    constants = sorted(
        {
            _python_constant_name(operation.fields)
            for operation in spec.operations
            if isinstance(operation, SearchReadOperation)
        }
    )
    attrs_name = f"_Generated{class_name}Attrs"
    imported_names = [*constants, attrs_name]
    import_block = "\n".join(f"    {name}," for name in imported_names)
    module_docstring = (
        f'"""Generated {class_name.lower()} namespace metadata and simple '
        'asynchronous operations."""'
    )
    lines = [
        module_docstring,
        "",
        f"# {_GENERATED_MARKER}",
        f"# Source: {source_path.as_posix()}",
        f"# Spec digest: sha256:{digest}",
        "",
        "from __future__ import annotations",
        "",
    ]
    if uses_any:
        lines.extend(["from typing import Any", ""])
    lines.extend(
        [
            "from vodoo.aio._domain import AsyncDomainNamespace",
            f"from vodoo.generated.{spec.namespace} import (",
            import_block,
            ")",
            "",
            "",
            (f"class GeneratedAsync{class_name}Namespace({attrs_name}, AsyncDomainNamespace):"),
            f'    """Generated asynchronous {class_name.lower()} namespace operations."""',
        ]
    )
    operations = _python_operations(spec, async_mode=True)
    if operations:
        lines.extend(["", operations])
    lines.append("")
    return "\n".join(lines)


def _swift_string_list(values: list[str]) -> str:
    return "[" + ", ".join(_typescript_literal(value) for value in values) + "]"


def _swift_json(value: object) -> str:  # noqa: PLR0911
    if value is None:
        return ".null"
    if value is True:
        return ".bool(true)"
    if value is False:
        return ".bool(false)"
    if isinstance(value, str):
        return f".string({_typescript_literal(value)})"
    if isinstance(value, int | float):
        return f".number({value})"
    if isinstance(value, list):
        return ".array([" + ", ".join(_swift_json(item) for item in value) + "])"
    if isinstance(value, dict):
        return (
            ".object(["
            + ", ".join(
                f"{_typescript_literal(key)}: {_swift_json(item)}" for key, item in value.items()
            )
            + "])"
        )
    raise TypeError(f"Unsupported Swift literal: {type(value).__name__}")


def _render_swift_operation(spec: NamespaceSpec, operation: OperationSpec) -> str:
    if isinstance(operation, WriteOperation):
        parameter = operation.id_parameter
        return "\n".join(
            [
                f"    /// {operation.description}",
                f"    public func {operation.name}({parameter}: Int) async throws -> Bool {{",
                "        try await client.write(",
                f"            model: {_typescript_literal(operation.model)},",
                f"            ids: [{parameter}],",
                "            values: "
                + _swift_json(operation.values).removeprefix(".object(").removesuffix(")"),
                "        )",
                "    }",
            ]
        )
    assert isinstance(operation, SearchReadOperation)
    domain = operation.domain
    if domain is None:
        signature = ""
        domain_lines = ["        let domain: Domain = []"]
    else:
        parameter = domain.parameter
        optional = isinstance(domain, OptionalDomain | OptionalListDomain)
        signature = f"{parameter}: Int{'?' if optional else ''}{' = nil' if optional else ''}"
        value = (
            f".array([.integer({parameter})])"
            if isinstance(domain, OptionalListDomain)
            else f".integer({parameter})"
        )
        term = (
            f".array([.string({_typescript_literal(domain.field)}), "
            f".string({_typescript_literal(domain.operator)}), {value}])"
        )
        if optional:
            domain_lines = [
                "        let domain: Domain",
                f"        if let {parameter} {{ domain = [{term}] }} else {{ domain = [] }}",
            ]
        else:
            domain_lines = [f"        let domain: Domain = [{term}]"]
    fields = _swift_string_list(spec.field_sets[operation.fields])
    return "\n".join(
        [
            f"    /// {operation.description}",
            f"    public func {operation.name}({signature}) async throws -> [OdooRecord] {{",
            *domain_lines,
            "        return try await client.searchRead(",
            f"            model: {_typescript_literal(operation.model)},",
            "            domain: domain,",
            f"            fields: {fields},",
            "            limit: nil,",
            "            offset: 0,",
            f"            order: {_typescript_literal(operation.order)}",
            "        )",
            "    }",
        ]
    )


def render_swift(spec: NamespaceSpec) -> str:
    digest = _spec_digest(spec)
    availability = spec.availability
    max_version = str(availability.max_version) if availability.max_version is not None else "nil"
    detail = (
        _swift_string_list(spec.default_detail_fields)
        if spec.default_detail_fields is not None
        else "nil"
    )
    tag = _typescript_literal(spec.tag_model) if spec.tag_model is not None else "nil"
    lines = [
        f"// {_GENERATED_MARKER}",
        f"// Source: {_source_path(spec).as_posix()}",
        f"// Spec digest: sha256:{digest}",
        "",
        "import Foundation",
        "",
        f"open class Generated{spec.class_name}Namespace: DomainNamespace, @unchecked Sendable {{",
        "    public init(client: any OdooClientAPI) {",
        "        super.init(",
        "            client: client,",
        f"            model: {_typescript_literal(spec.model)},",
        f"            defaultFields: {_swift_string_list(spec.default_fields)},",
        f"            defaultDetailFields: {detail},",
        f"            tagModel: {tag},",
        f"            capabilities: {_swift_string_list(spec.capabilities)},",
        "            availability: NamespaceAvailability(",
        f"                module: {_typescript_literal(availability.module)},",
        f"                editions: {_swift_string_list(availability.editions)},",
        f"                minVersion: {availability.min_version},",
        f"                maxVersion: {max_version}",
        "            )",
        "        )",
        "    }",
    ]
    for operation in spec.operations:
        lines.extend(["", _render_swift_operation(spec, operation)])
    lines.extend(["}", ""])
    return "\n".join(lines)


def _rendered_outputs(spec: NamespaceSpec) -> dict[Path, str]:
    typescript, python, async_python, swift = _output_paths(spec)
    return {
        typescript: render_typescript(spec),
        python: render_python(spec),
        async_python: render_async_python(spec),
        swift: render_swift(spec),
    }


def render_python_security_groups(spec: SecurityGroupsSpec) -> str:
    lines = [
        '"""Generated canonical security group definitions."""',
        "",
        f"# {_GENERATED_MARKER}",
        f"# Source: {SECURITY_GROUPS_SPEC_PATH.as_posix()}",
        "",
        "from vodoo.security import (",
        "    AccessDefinition,",
        "    GroupDefinition,",
        "    RuleDefinition,",
        ")",
        "",
        "GROUP_DEFINITIONS: tuple[GroupDefinition, ...] = (",
    ]
    for group in spec.groups:
        lines.extend(
            [
                "    GroupDefinition(",
                f"        name={_python_literal(group.name)},",
                f"        comment={_python_literal(group.comment)},",
                "        access=(",
            ]
        )
        for item in group.access:
            values = ", ".join(
                [
                    _python_literal(item.model),
                    _python_literal(item.perm_read),
                    _python_literal(item.perm_write),
                    _python_literal(item.perm_create),
                    _python_literal(item.perm_unlink),
                ]
            )
            lines.append(f"            AccessDefinition({values}),")
        lines.append("        ),")
        if not group.rules:
            lines.append("        rules=(),")
        else:
            lines.append("        rules=(")
        for item in group.rules:
            lines.extend(
                [
                    "            RuleDefinition(",
                    f"                {_python_literal(item.model)},",
                    f"                {_python_literal(item.domain)},",
                    f"                {_python_literal(item.perm_read)},",
                    f"                {_python_literal(item.perm_write)},",
                    f"                {_python_literal(item.perm_create)},",
                    f"                {_python_literal(item.perm_unlink)},",
                    "            ),",
                ]
            )
        if group.rules:
            lines.append("        ),")
        lines.append("    ),")
    lines.extend([")", ""])
    return "\n".join(lines)


def render_typescript_security_groups(spec: SecurityGroupsSpec) -> str:
    lines = [
        f"// {_GENERATED_MARKER}",
        f"// Source: {SECURITY_GROUPS_SPEC_PATH.as_posix()}",
        "",
        "export interface AccessDefinition {",
        "  readonly model: string;",
        "  readonly permRead: boolean;",
        "  readonly permWrite: boolean;",
        "  readonly permCreate: boolean;",
        "  readonly permUnlink: boolean;",
        "}",
        "",
        "export interface RuleDefinition extends AccessDefinition {",
        "  readonly domain: string;",
        "}",
        "",
        "export interface GroupDefinition {",
        "  readonly name: string;",
        "  readonly comment: string;",
        "  readonly access: readonly AccessDefinition[];",
        "  readonly rules?: readonly RuleDefinition[];",
        "}",
        "",
        "const access = (",
        "  model: string, permRead: boolean, permWrite: boolean,",
        "  permCreate: boolean, permUnlink: boolean,",
        "): AccessDefinition => ({ model, permRead, permWrite, permCreate, permUnlink });",
        "",
        "const rule = (",
        "  model: string, domain: string, permRead: boolean, permWrite: boolean,",
        "  permCreate: boolean, permUnlink: boolean,",
        "): RuleDefinition => ({ model, domain, permRead, permWrite, permCreate, permUnlink });",
        "",
        "export const GROUP_DEFINITIONS: readonly GroupDefinition[] = Object.freeze([",
    ]
    for group in spec.groups:
        lines.extend(
            [
                "  {",
                f"    name: {_typescript_literal(group.name)},",
                f"    comment: {_typescript_literal(group.comment)},",
                "    access: [",
            ]
        )
        for item in group.access:
            values = ",".join(
                _typescript_literal(value)
                for value in (
                    item.model,
                    item.perm_read,
                    item.perm_write,
                    item.perm_create,
                    item.perm_unlink,
                )
            )
            lines.append(f"      access({values}),")
        lines.extend(["    ],", "    rules: ["])
        for item in group.rules:
            values = ",".join(
                _typescript_literal(value)
                for value in (
                    item.model,
                    item.domain,
                    item.perm_read,
                    item.perm_write,
                    item.perm_create,
                    item.perm_unlink,
                )
            )
            lines.append(f"      rule({values}),")
        lines.extend(["    ],", "  },"])
    lines.extend(["]);", ""])
    return "\n".join(lines)


def render_api_manifest(specs: tuple[NamespaceSpec, ...]) -> str:
    manifest = {
        "specVersion": 1,
        "services": {
            "generic": {"targets": ["python", "asyncPython", "typescript", "swift"]},
            "security": {"targets": ["python", "typescript"]},
            "timer": {"targets": ["python", "asyncPython", "typescript"]},
        },
        "namespaces": [
            {
                "namespace": spec.namespace,
                "className": spec.class_name,
                "model": spec.model,
                "capabilities": spec.capabilities,
                "availability": spec.availability.model_dump(mode="json", by_alias=True),
                "generatedOperations": [
                    {
                        "name": operation.name,
                        "kind": operation.kind,
                        "targets": ["python", "asyncPython", "typescript", "swift"],
                    }
                    for operation in spec.operations
                ],
                "customOperations": [
                    operation.model_dump(mode="json", by_alias=True)
                    for operation in spec.custom_operations
                ],
            }
            for spec in specs
        ],
    }
    return json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"


def _all_rendered_outputs(root: Path) -> dict[Path, str]:
    specs = _load_specs(root)
    security_groups = _load_security_groups(root)
    outputs = {path: content for spec in specs for path, content in _rendered_outputs(spec).items()}
    outputs[PYTHON_SECURITY_GROUPS_PATH] = render_python_security_groups(security_groups)
    outputs[TYPESCRIPT_SECURITY_GROUPS_PATH] = render_typescript_security_groups(security_groups)
    outputs[API_MANIFEST_PATH] = render_api_manifest(specs)
    return outputs


def _python_methods(path: Path) -> set[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    return {
        node.name
        for item in tree.body
        if isinstance(item, ast.ClassDef)
        for node in item.body
        if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef)
    }


def missing_custom_implementations(root: Path | None = None) -> tuple[str, ...]:
    root = root or Path.cwd()
    missing: list[str] = []
    ts_stems = {"account_moves": "account-moves", "project_tasks": "tasks"}
    for spec in _load_specs(root):
        python_path = root / "src/vodoo" / f"{spec.namespace}.py"
        async_path = root / "src/vodoo/aio" / f"{spec.namespace}.py"
        typescript_path = (
            root
            / "packages/typescript/src/namespaces"
            / f"{ts_stems.get(spec.namespace, spec.namespace)}.ts"
        )
        swift_paths = sorted((root / "Sources/Vodoo").glob("*.swift"))
        python_methods = _python_methods(python_path) if python_path.exists() else set()
        async_methods = _python_methods(async_path) if async_path.exists() else set()
        typescript_source = (
            typescript_path.read_text(encoding="utf-8") if typescript_path.exists() else ""
        )
        swift_source = "\n".join(path.read_text(encoding="utf-8") for path in swift_paths)
        for operation in spec.custom_operations:
            python_name = _snake_case(operation.name)
            if "python" in operation.targets and python_name not in python_methods:
                missing.append(f"python:{spec.namespace}.{python_name}")
            if "asyncPython" in operation.targets and python_name not in async_methods:
                missing.append(f"asyncPython:{spec.namespace}.{python_name}")
            if "typescript" in operation.targets and not re.search(
                rf"\b{re.escape(operation.name)}\s*\(", typescript_source
            ):
                missing.append(f"typescript:{spec.namespace}.{operation.name}")
            if "swift" in operation.targets and not re.search(
                rf"\bfunc\s+{re.escape(operation.name)}\s*\(", swift_source
            ):
                missing.append(f"swift:{spec.namespace}.{operation.name}")
    return tuple(missing)


def generate(root: Path | None = None) -> tuple[Path, ...]:
    root = root or Path.cwd()
    outputs = _all_rendered_outputs(root)
    generated: list[Path] = []
    for relative_path, content in outputs.items():
        output = root / relative_path
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(content, encoding="utf-8")
        generated.append(output)
    return tuple(generated)


def _orphaned_outputs(root: Path, expected: set[Path]) -> tuple[Path, ...]:
    orphans: list[Path] = []
    for directory, suffix in (
        (TYPESCRIPT_OUTPUT_DIR, "*.ts"),
        (PYTHON_OUTPUT_DIR, "*.py"),
        (ASYNC_PYTHON_OUTPUT_DIR, "*.py"),
        (SWIFT_OUTPUT_DIR, "*.swift"),
    ):
        for output in sorted((root / directory).glob(suffix)):
            relative = output.relative_to(root)
            if relative in expected:
                continue
            if _GENERATED_MARKER in output.read_text(encoding="utf-8"):
                orphans.append(relative)
    return tuple(orphans)


def stale_outputs(root: Path | None = None) -> tuple[Path, ...]:
    root = root or Path.cwd()
    outputs = _all_rendered_outputs(root)
    stale = [
        relative_path
        for relative_path, expected in outputs.items()
        if not (root / relative_path).exists()
        or (root / relative_path).read_text(encoding="utf-8") != expected
    ]
    stale.extend(_orphaned_outputs(root, set(outputs)))
    return tuple(stale)


def check_generated(root: Path | None = None) -> bool:
    return not stale_outputs(root) and not missing_custom_implementations(root)
